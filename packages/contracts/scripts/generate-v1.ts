/**
 * The hand-written zod contracts of `/v1` (src/v1) stay the single source of truth for read models and
 * writes. This script exports the ones the local engine serves as JSON Schema (schemas-v1/) and generates
 * Pydantic models from them (python/firra_contracts/generated_v1/), so the Python engine returns exactly
 * the shapes the Swift client and the MCP tools expect. Run through `pnpm codegen` (committed output).
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import * as v1 from "../src/v1/index.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const jsonOut = join(root, "schemas-v1");
const pyOut = join(root, "python", "firra_contracts", "generated_v1");

export const MODELS = [
  "attentionResponse",
  "changesResponse",
  "clientsResponse",
  "clientDetailResponse",
  "meResponse",
  "meetingsResponse",
  "decisionsResponse",
  "feedbackRequest",
  "outcomeRequest",
  "mutationResponse",
  "routinesResponse",
  "routineEnabledRequest",
  "replayRunsResponse",
  "replayClientResponse",
  "requestReplayRequest",
  "timelineResponse",
  "evidenceResponse",
  "evidenceItem",
  "createClientRequest",
  "updateClientRequest",
  "clientDomainsRequest",
  "clientPolicyRequest",
  "saveServiceRequest",
  "setupIdResponse",
  "servicesResponse",
  "setupClientsResponse",
  "clientDomainsResponse",
  "auditResponse",
  "mcpClientChange",
  "mcpCommitments",
  "mcpStakeholders",
  "mcpUnknowns",
  "mcpEvidence",
  "mcpReplay",
] as const;

/** zod adds a regex `pattern` next to `format`; the generated date and uuid types are not strings, so drop it. */
function dropRedundantPatterns(node: unknown): void {
  if (Array.isArray(node)) {
    node.forEach(dropRedundantPatterns);
    return;
  }
  if (node === null || typeof node !== "object") return;
  const record = node as Record<string, unknown>;
  if (["date-time", "date", "uuid", "email"].includes(String(record.format))) delete record.pattern;
  Object.values(record).forEach(dropRedundantPatterns);
}

const snake = (name: string) => name.replace(/([A-Z])/g, "_$1").toLowerCase();
const pascal = (name: string) => name.charAt(0).toUpperCase() + name.slice(1);

rmSync(jsonOut, { recursive: true, force: true });
mkdirSync(jsonOut, { recursive: true });
for (const name of MODELS) {
  const schema = (v1 as Record<string, unknown>)[name];
  if (!schema || typeof (schema as { _zod?: unknown })._zod !== "object") {
    throw new Error(`generate-v1: ${name} is not an exported zod schema`);
  }
  const json = z.toJSONSchema(schema as z.ZodType, {
    target: "draft-2020-12",
    io: "output",
    unrepresentable: "any",
  }) as Record<string, unknown>;
  dropRedundantPatterns(json);
  json.title = pascal(name);
  json.$id = `https://firra.app/contracts/v1/${snake(name)}.json`;
  writeFileSync(join(jsonOut, `${snake(name)}.json`), `${JSON.stringify(json, null, 2)}\n`);
}

rmSync(pyOut, { recursive: true, force: true });
execFileSync(
  "uv",
  [
    "run",
    "--frozen",
    "datamodel-codegen",
    "--input",
    jsonOut,
    "--input-file-type",
    "jsonschema",
    "--output",
    pyOut,
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.12",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-title-as-name",
    "--use-subclass-enum",
    "--field-constraints",
    "--use-double-quotes",
    "--disable-timestamp",
    "--custom-file-header",
    "# Generated by packages/contracts/scripts/generate-v1.ts. Do not edit.",
    "--formatters",
    "ruff-format",
  ],
  { cwd: root, stdio: "inherit" },
);
process.stdout.write(
  `contracts: exported ${MODELS.length} v1 models to JSON Schema and Pydantic\n`,
);
